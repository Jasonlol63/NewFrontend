/** The back end's message in the page language (Chinese when listed there), else unchanged. */
export function localizeBackend(message) {
  if (typeof message !== "string" || !message) return message;
  if (!String(i18n.language ?? "").startsWith("zh")) return message;
  const text = message.trim();
  for (const [pattern, zh] of ZH) {
    if (pattern.test(text)) return text.replace(pattern, zh);
  }
  return message;
}
